def search_knowledge(query, is_admin=False):
    q = query.lower().strip()

    # 1. Проверяем FAQ
    for item in SITE_KNOWLEDGE["faq"]["questions"]:
        if _match_query(q, item["q"]):
            return {"success": True, "answer": item["a"], "source": "faq"}

    # 2. Проверяем функции пользователя
    for func in SITE_KNOWLEDGE["roles"]["user"]["functions"]:
        if _match_triggers(q, func["triggers"]):
            return {"success": True, "answer": func["answer"], "source": "user_guide"}

    # 3. Проверяем функции админа
    if is_admin:
        for func in SITE_KNOWLEDGE["roles"]["admin"]["functions"]:
            if _match_triggers(q, func["triggers"]):
                return {"success": True, "answer": func["answer"], "source": "admin_guide"}

    # 4. НОВОЕ: проверяем HUMAN_ANSWERS
    from ai_model.human_dataset import HUMAN_DATASET
    for item in HUMAN_DATASET:
        if item['intent'] in ['site_knowledge', 'help', 'greeting', 'fallback']:
            if _match_query(q, item['question']):
                return {"success": True, "answer": item['answer'], "source": "human_dataset"}

    return None


def _match_query(query, target):
    """Проверяет, соответствует ли запрос целевому вопросу"""
    query_words = set(query.lower().split())
    target_words = set(target.lower().split())

    # Если есть значительное пересечение
    common = query_words & target_words
    return len(common) >= 2 or any(w in query for w in target_words if len(w) > 4)


def _match_triggers(query, triggers):
    """Проверяет, соответствует ли запрос триггерам"""
    q = query.lower()
    return any(trigger.lower() in q for trigger in triggers)


